"""Extract the molecular ``[Ln(DOTA)]-`` unit from the water-free LnDOTA CCDC file.

The deposition (CCDC 2281329, 2281615-2281620) puts every lanthanide on the
four-fold axis of space group ``P4bm`` with unit occupancy, so the ligand cage is
generated by that axis and the extracted cluster carries an exact crystallographic
``C4``. That makes these structures the positive control for a symmetry score: the
forbidden channels have to sit at the numerical floor.

Counter-ions and lattice solvent are dropped, since only the coordinated ligand
defines the field the metal experiences.
"""

from __future__ import annotations

import warnings
from collections import deque
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import numpy as np

LANTHANIDES: Tuple[str, ...] = (
    "Y",
    "La",
    "Ce",
    "Pr",
    "Nd",
    "Sm",
    "Eu",
    "Gd",
    "Tb",
    "Dy",
    "Ho",
    "Er",
    "Tm",
    "Yb",
    "Lu",
)

# Cordero covalent radii, only for the elements this ligand contains.
COVALENT_RADII: Dict[str, float] = {"H": 0.31, "C": 0.76, "N": 0.71, "O": 0.66}

EXCLUDED_ELEMENTS: Tuple[str, ...] = ("Cl", "Na", "K")

METAL_LIGAND_CUTOFF = 2.9
BOND_TOLERANCE = 1.30


@dataclass(frozen=True)
class LnDotaCluster:
    """One extracted ``[Ln(DOTA)]-`` cluster, centred on the metal."""

    lanthanide: str
    ccdc_number: str
    space_group: str
    lattice_a: float
    symbols: Tuple[str, ...]
    coords: np.ndarray
    axis: np.ndarray

    @property
    def formula(self) -> str:
        from collections import Counter

        counts = Counter(self.symbols)
        ordered = [self.lanthanide] + sorted(k for k in counts if k != self.lanthanide)
        return " ".join(f"{k}{counts[k]}" for k in ordered)


def _dominant_element(site) -> str:
    return max(site.species, key=site.species.get).symbol


def _bonded(element_a: str, element_b: str, distance: float) -> bool:
    if element_a in LANTHANIDES or element_b in LANTHANIDES:
        return distance < METAL_LIGAND_CUTOFF
    radius_a = COVALENT_RADII.get(element_a)
    radius_b = COVALENT_RADII.get(element_b)
    if radius_a is None or radius_b is None:
        return False
    return distance < BOND_TOLERANCE * (radius_a + radius_b)


def _walk_bonded_cluster(structure, start_index: int) -> List[Tuple[str, np.ndarray]]:
    """Breadth-first walk over bonds, unwrapping periodic images as it goes."""
    origin = (start_index, (0, 0, 0))
    visited = {origin}
    queue = deque([origin])
    atoms: List[Tuple[str, np.ndarray]] = []

    while queue:
        index, image = queue.popleft()
        site = structure[index]
        shift = structure.lattice.get_cartesian_coords(image)
        element = _dominant_element(site)
        atoms.append((element, site.coords + shift))

        for neighbor in structure.get_neighbors(site, r=METAL_LIGAND_CUTOFF):
            neighbor_element = _dominant_element(neighbor)
            if neighbor_element in EXCLUDED_ELEMENTS:
                continue
            if not _bonded(element, neighbor_element, float(neighbor.nn_distance)):
                continue
            key = (
                neighbor.index,
                tuple(int(a) + int(b) for a, b in zip(image, neighbor.image)),
            )
            if key in visited:
                continue
            visited.add(key)
            queue.append(key)

    return atoms


def donor_axis(symbols: Sequence[str], coords: np.ndarray, donor: str = "N") -> np.ndarray:
    """Pseudo four-fold axis: the normal of the plane through the macrocycle donors.

    The four DOTA nitrogens are always coordinated, so their best-fit plane fixes the
    axis without an orientation search. Used for the water-capped comparison
    structures, which come from non-tetragonal crystals.
    """
    coords = np.asarray(coords, dtype=float)
    metal = coords[0]
    picked = np.asarray(
        [
            coords[i]
            for i, symbol in enumerate(symbols)
            if symbol == donor and np.linalg.norm(coords[i] - metal) < METAL_LIGAND_CUTOFF
        ]
    )
    if len(picked) < 3:
        raise ValueError(f"Need at least 3 coordinating {donor} atoms, found {len(picked)}.")
    centred = picked - picked.mean(axis=0, keepdims=True)
    _, _, right = np.linalg.svd(centred)
    axis = right[-1]
    return axis / np.linalg.norm(axis)


def self_match_rms(
    symbols: Sequence[str],
    coords: np.ndarray,
    axis: np.ndarray,
    fold: int,
) -> float:
    """RMS displacement after rotating by ``2*pi/fold`` and rematching same-element atoms."""
    axis = np.asarray(axis, dtype=float)
    axis = axis / np.linalg.norm(axis)
    angle = 2.0 * np.pi / int(fold)
    cross = np.array(
        [
            [0.0, -axis[2], axis[1]],
            [axis[2], 0.0, -axis[0]],
            [-axis[1], axis[0], 0.0],
        ]
    )
    rotation = np.eye(3) + np.sin(angle) * cross + (1.0 - np.cos(angle)) * cross @ cross
    rotated = coords @ rotation.T

    deviations = []
    for index, point in enumerate(rotated):
        candidates = [j for j, s in enumerate(symbols) if s == symbols[index]]
        deviations.append(min(float(np.linalg.norm(coords[j] - point)) for j in candidates))
    return float(np.sqrt(np.mean(np.square(deviations))))


def load_lndota_clusters(cif_path: str | Path) -> List[LnDotaCluster]:
    """Parse every block of the multi-block CIF into one metal-centred cluster."""
    from pymatgen.io.cif import CifParser

    cif_path = Path(cif_path)
    ccdc_numbers = _scan_ccdc_numbers(cif_path)

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        parser = CifParser(str(cif_path))
        structures = parser.parse_structures(primitive=False)

    clusters: List[LnDotaCluster] = []
    for block_index, structure in enumerate(structures):
        metal_indices = [
            i for i, site in enumerate(structure) if _dominant_element(site) in LANTHANIDES
        ]
        if not metal_indices:
            raise ValueError(f"Block {block_index} of {cif_path.name} has no lanthanide site.")
        # Several formula units per cell give symmetry-equivalent metal sites; either works.
        metal_index = metal_indices[0]
        atoms = _walk_bonded_cluster(structure, metal_index)

        symbols = tuple(element for element, _ in atoms)
        coords = np.asarray([position for _, position in atoms], dtype=float)
        coords = coords - coords[0]

        # The four-fold axis of P4bm runs along c.
        axis = structure.lattice.matrix[2]
        axis = axis / np.linalg.norm(axis)

        clusters.append(
            LnDotaCluster(
                lanthanide=symbols[0],
                ccdc_number=ccdc_numbers[block_index],
                space_group=str(structure.get_space_group_info()[0]),
                lattice_a=float(structure.lattice.a),
                symbols=symbols,
                coords=coords,
                axis=axis,
            )
        )
    return clusters


def _scan_ccdc_numbers(cif_path: Path) -> List[str]:
    numbers: List[str] = []
    for line in cif_path.read_text(encoding="utf-8", errors="ignore").splitlines():
        if "_database_code_depnum_ccdc_archive" in line:
            numbers.append(line.split()[-1].strip("'\""))
    return numbers


